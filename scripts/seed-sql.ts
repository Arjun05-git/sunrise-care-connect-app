/**
 * Builds the two seed files (see scripts/generate-seed.ts, which writes them):
 *   reference.sql  master data and defaults only (ICD-10, drugs and rules, templates, consent / legal texts,
 *                  default settings). No people, no credentials: safe to load into ANY environment.
 *   demo.sql       the demo hospital: logins with known passwords, doctors, patients, appointments in every state,
 *                  payments, prescriptions. Refuses to run unless the database is declared as demo.
 * Demo timestamps are relative to `now` (so "today" always has consultations); the reference file has none.
 */
import { buildSeed } from '../src/data/seed/index';
import { DEMO, LEGAL_DOCUMENTS } from '../src/data/seed/org';
import { generateSlotCandidates } from '../src/domain/rules';
import { istDateKey } from '../src/domain/time';

/** Tables the reference seed may fill: master data and defaults. Nothing about people or credentials. */
export const REFERENCE_TABLES = ['icd10_master', 'note_templates', 'drug_master', 'drug_rules', 'follow_up_policy', 'app_settings', 'content_versions', 'notification_templates'];

export function buildSeedSql(now: Date) {
const db = buildSeed(now);
const ref: string[] = [];
const demo: string[] = [];
let out = demo;
const q = (v: unknown): string => {
  if (v === null || v === undefined) return 'null';
  if (typeof v === 'number') return String(v);
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  if (Array.isArray(v) && v.every((x) => typeof x === 'string')) return v.length ? `array[${v.map(q).join(',')}]` : `'{}'`;
  if (typeof v === 'object') return `${q(JSON.stringify(v))}::jsonb`;
  return `'${String(v).replace(/'/g, "''")}'`;
};
const arr = (v: string[], type: string) => (v.length ? `array[${v.map(q).join(',')}]::${type}[]` : `'{}'::${type}[]`);
function insert<T extends object>(table: string, rows: T[], cols: (keyof T)[], overrides: Partial<Record<keyof T, (r: T) => string>> = {}, suffix = '') {
  if (!rows.length) return;
  out.push(`insert into ${table} (${cols.join(', ')}) values`);
  out.push(rows.map((r) => `  (${cols.map((c) => (overrides[c] ? overrides[c]!(r) : q(r[c]))).join(', ')})`).join(',\n') + suffix + ';\n');
}

ref.push(`-- Reference data: master tables and defaults. No people, no credentials: safe to load into ANY environment.
-- GENERATED by scripts/generate-seed.ts (npm run db:seed:generate). Deterministic, so changes show up in review.
-- Clinical content (drug lists and rules, ICD-10, note templates) and the consent / legal texts are drafts:
-- have them signed off by the hospital before go-live.
begin;
-- pgcrypto and friends live in the "extensions" schema on hosted Supabase, in public on plain Postgres
set local search_path = public, extensions;
set local app.audit_reason = 'reference data';
`);
demo.push(`-- AUTO-GENERATED by scripts/generate-seed.ts at ${db.seeded_at}. Demo data only – no real patients.
-- Demo logins: patient ${DEMO.patientPhone} / doctor ${DEMO.doctorPhone} (OTP ${DEMO.otp}, PIN ${DEMO.doctorPin}) / admin ${DEMO.adminEmail} / ${DEMO.adminPassword}
-- Load reference.sql first. This file creates accounts with KNOWN passwords, so it refuses to run anywhere but a
-- database declared as demo:  ALTER DATABASE <name> SET app.environment = 'demo';
begin;
do $$ begin
  if coalesce(current_setting('app.environment', true), '') <> 'demo' then
    raise exception 'demo seed refused: this database is not declared as demo (ALTER DATABASE <name> SET app.environment = ''demo'')';
  end if;
end $$;
-- Audit triggers fire during seeding; label those rows.
-- pgcrypto (crypt, gen_salt) is in the "extensions" schema on hosted Supabase, in public on plain Postgres
set local search_path = public, extensions;
set local app.audit_reason = 'seed data';
-- historical demo data: don't queue messages for it
set local app.suppress_notifications = 'on';
`);

// ---- auth users (trigger creates profile + patient role; we correct roles afterwards)
// GoTrue scans its token columns as non-null strings, so they are set to ''.
const staffEmails = new Set(Object.keys(db.auth.admin_passwords));
const TOKEN_COLS = ['confirmation_token', 'recovery_token', 'email_change_token_new', 'email_change', 'email_change_token_current', 'phone_change', 'phone_change_token', 'reauthentication_token'];
out.push(`insert into auth.users (instance_id, id, aud, role, email, phone, encrypted_password, email_confirmed_at, phone_confirmed_at, raw_app_meta_data, raw_user_meta_data, created_at, updated_at, ${TOKEN_COLS.join(', ')}) values`);
out.push(
  db.profiles
    .map(
      (p) =>
        `  ('00000000-0000-0000-0000-000000000000', ${q(p.id)}, 'authenticated', 'authenticated', ${q(p.email)}, ${q(p.phone?.replace('+', '') ?? null)}, ${
          p.email && staffEmails.has(p.email) ? `crypt(${q(db.auth.admin_passwords[p.email])}, gen_salt('bf'))` : "''"
        }, ${p.email ? 'now()' : 'null'}, ${p.phone ? 'now()' : 'null'}, ${q({ provider: p.email ? 'email' : 'phone', providers: [p.email ? 'email' : 'phone'] })}, ${q({ full_name: p.full_name })}, now(), now(), ${TOKEN_COLS.map(() => "''").join(', ')})`,
    )
    .join(',\n') + ';\n',
);
// Identities (real Supabase/GoTrue only; the plain-Postgres test shim has no auth.identities).
out.push(`do $$ begin
  if to_regclass('auth.identities') is not null then
    insert into auth.identities (id, provider_id, user_id, identity_data, provider, created_at, updated_at, last_sign_in_at)
    select gen_random_uuid(), coalesce(email, phone), id,
           jsonb_build_object('sub', id::text, 'email', email, 'phone', phone, 'email_verified', true, 'phone_verified', true),
           case when email is not null then 'email' else 'phone' end, now(), now(), now()
    from auth.users where id in (${db.profiles.map((p) => q(p.id)).join(',')})
    on conflict do nothing;
  end if;
end $$;
`);
insert('profiles', db.profiles, ['id', 'full_name', 'phone', 'email', 'preferred_language', 'created_at'], {}, '\non conflict (id) do update set full_name = excluded.full_name, phone = excluded.phone, email = excluded.email');
out.push(`delete from user_roles where user_id in (${db.profiles.map((p) => q(p.id)).join(',')});`);

insert('hospitals', db.hospitals, ['id', 'name', 'city', 'address', 'phone', 'emergency_phone', 'active']);
insert('user_roles', db.user_roles, ['user_id', 'role', 'hospital_id']);
insert('departments', db.departments, ['id', 'name', 'name_ml', 'icon', 'active']);
insert('doctors', db.doctors, ['id', 'profile_id', 'full_name', 'photo_url', 'qualification', 'registration_no', 'registration_council', 'verification_status', 'experience_years', 'languages', 'hospital_id', 'department_id', 'bio', 'modes', 'slot_minutes', 'rating_avg', 'rating_count', 'signature_url', 'phone', 'active'], {
  languages: (r) => arr(r.languages, 'text'),
  modes: (r) => arr(r.modes, 'consult_mode'),
});
out.push(`insert into doctor_secrets (profile_id, pin_hash) select profile_id, crypt('${DEMO.doctorPin}', gen_salt('bf')) from doctors;\n`);
insert('doctor_preferences', Object.entries(db.doctor_prefs).map(([doctor_id, prefs]) => ({ doctor_id, prefs })), ['doctor_id', 'prefs']);
insert('doctor_availability', db.doctor_availability, ['id', 'doctor_id', 'kind', 'weekday', 'start_time', 'end_time', 'block_date_from', 'block_date_to', 'reason']);
insert('holidays', db.holidays, ['id', 'hospital_id', 'date', 'name']);
insert('patients', db.patients, ['id', 'owner_user_id', 'full_name', 'date_of_birth', 'gender', 'phone', 'email', 'address', 'blood_group', 'allergies', 'his_mrn', 'abha_number', 'is_primary', 'created_at'], {
  allergies: (r) => arr(r.allergies, 'text'),
});
insert('dependents', db.dependents, ['id', 'owner_patient_id', 'patient_id', 'relation']);
insert('consents', db.consents, ['id', 'user_id', 'consent_type', 'version', 'granted', 'granted_at', 'withdrawn_at', 'user_agent']);

// Bookable slots for the next 14 days from each doctor's weekly availability (skipping holidays,
// leave blocks and anything overlapping the seeded appointment slots).
const extraSlots = db.doctors.flatMap((d) => {
  const mine = db.slots.filter((s) => s.doctor_id === d.id);
  return generateSlotCandidates(d, db.doctor_availability.filter((a) => a.doctor_id === d.id), db.holidays, istDateKey(now), 14)
    .filter((c) => !mine.some((s) => s.start_at < c.end_at && s.end_at > c.start_at))
    .map((c) => ({ id: crypto.randomUUID(), doctor_id: d.id, start_at: c.start_at, end_at: c.end_at, status: 'open', held_until: null }));
});
insert('slots', [...db.slots, ...extraSlots], ['id', 'doctor_id', 'start_at', 'end_at', 'status', 'held_until'], {}, '');
insert('appointments', db.appointments, ['id', 'ref_code', 'patient_id', 'booked_by_user_id', 'doctor_id', 'hospital_id', 'department_id', 'slot_id', 'start_at', 'end_at', 'mode', 'consult_type', 'fee_amount', 'is_free', 'status', 'outcome', 'outcome_reason', 'hold_expires_at', 'fee_override_reason', 'extended_minutes', 'doctor_joined_at', 'patient_joined_at', 'completed_at', 'cancelled_at', 'created_at']);
for (const a of db.appointments) {
  const sets = [
    a.index_appointment_id && `index_appointment_id = ${q(a.index_appointment_id)}`,
    a.rescheduled_from_id && `rescheduled_from_id = ${q(a.rescheduled_from_id)}`,
    a.rescheduled_to_id && `rescheduled_to_id = ${q(a.rescheduled_to_id)}`,
  ].filter(Boolean);
  if (sets.length) out.push(`update appointments set ${sets.join(', ')} where id = ${q(a.id)};`);
}
for (const s of db.slots.filter((x) => x.appointment_id)) out.push(`update slots set appointment_id = ${q(s.appointment_id)} where id = ${q(s.id)};`);
out.push('');
insert('appointment_symptoms', db.appointment_symptoms, ['appointment_id', 'body_area', 'symptoms', 'duration', 'severity', 'description', 'voice_note_path', 'vitals', 'allergies', 'current_medicines', 'past_history'], {
  symptoms: (r) => arr(r.symptoms, 'text'),
});
insert('documents', db.documents, ['id', 'patient_id', 'appointment_id', 'uploaded_by', 'tag', 'file_name', 'mime_type', 'size_bytes', 'storage_path', 'created_at']);
insert('payments', db.payments, ['id', 'appointment_id', 'provider', 'provider_order_id', 'provider_payment_id', 'amount', 'currency', 'method', 'status', 'settled', 'settlement_id', 'created_at', 'captured_at']);
insert('refunds', db.refunds, ['id', 'payment_id', 'appointment_id', 'amount', 'reason', 'status', 'provider_refund_id', 'initiated_by', 'created_at', 'processed_at']);
out = ref;
insert('icd10_master', db.icd10_master, ['code', 'description']);
// system-wide templates are reference data; a doctor's personal templates need that doctor, so they go with the demo
insert('note_templates', db.note_templates.filter((t) => !t.doctor_id), ['id', 'doctor_id', 'name', 'body']);
out = demo;
insert('note_templates', db.note_templates.filter((t) => t.doctor_id), ['id', 'doctor_id', 'name', 'body']);
out = ref;
insert('drug_master', db.drug_master, ['id', 'name', 'generic_name', 'form', 'strength', 'category', 'schedule', 'interaction_groups', 'allergy_class', 'default_dose', 'default_frequency', 'default_route'], {
  interaction_groups: (r) => arr(r.interaction_groups, 'text'),
});
insert('drug_rules', db.drug_rules, ['id', 'category', 'mode', 'consult_type', 'allowed', 'note']);
out = demo;
insert('consultations', db.consultations, ['id', 'appointment_id', 'doctor_id', 'patient_id', 'chief_complaint', 'history', 'examination', 'diagnoses', 'advice', 'investigations', 'follow_up_date', 'status', 'updated_at']);
// prescriptions: insert as draft, add items, then finalise (immutability trigger allows draft → final)
insert('prescriptions', db.prescriptions, ['id', 'appointment_id', 'doctor_id', 'patient_id', 'version', 'parent_prescription_id', 'addendum_reason', 'status', 'verification_code', 'advice', 'investigations', 'follow_up_date', 'diagnoses', 'finalized_at', 'created_at'], {
  status: () => `'draft'`,
});
insert('prescription_items', db.prescriptions.flatMap((p) => p.items.map((it, i) => ({ ...it, position: i }))), ['id', 'prescription_id', 'drug_id', 'drug_name', 'strength', 'form', 'dose', 'frequency', 'duration', 'route', 'instructions', 'position']);
out.push(`update prescriptions set status = 'final' where id in (${db.prescriptions.filter((p) => p.status === 'final').map((p) => q(p.id)).join(',')});\n`);

out = ref;
out.push(`insert into follow_up_policy (id, free_window_days, free_follow_up_count, match_rule) values (1, ${db.follow_up_policy.free_window_days}, ${db.follow_up_policy.free_follow_up_count}, ${q(db.follow_up_policy.match_rule)});\n`);
out = demo;
insert('fee_config', db.fee_config, ['id', 'scope', 'doctor_id', 'department_id', 'mode', 'consult_type', 'amount']);
// Reference defaults = what production starts with. Doctor step-up and staff MFA are NOT set here (a missing value
// means "required"), the HIS / LeadSquared integrations start OFF and are switched on deliberately.
const { public_url: _pu, require_doctor_step_up: _st, staff_mfa_required: _mfa, ...sharedSettings } = db.app_settings as Record<string, unknown>;
const toRows = (o: Record<string, unknown>) => Object.entries(o).map(([key, value]) => ({ key, value }));
const jsonb = { value: (r: { key: string; value: unknown }) => `${q(JSON.stringify(r.value))}::jsonb` };
out = ref;
insert('app_settings', toRows({
  ...sharedSettings,
  // paise per message (WhatsApp utility conversation, SMS per 160-character part); admin-editable in the Outbox
  notification_costs: { whatsapp: 13, sms: 25, push: 0 }, notification_quiet_hours: { start: '21:00', end: '08:00' }, feedback_delay_minutes: 120,
  integrations: { his: false, leadsquared: false },
}), ['key', 'value'], jsonb);
out = demo;
// Demo overrides on top of the reference defaults.
insert('app_settings', toRows({
  public_url: 'http://localhost:5173',
  require_doctor_step_up: false,   // so the demo OTP login works without the PIN step
  staff_mfa_required: false,       // honoured only where app.environment = 'demo' (migration 019)
  integrations: (db.app_settings as Record<string, unknown>).integrations,
}), ['key', 'value'], jsonb, '\non conflict (key) do update set value = excluded.value');
// versioned consent & legal content (Admin → Content publishes new revisions / versions)
const texts = db.app_settings.consent_texts as Record<string, { en: string; ml: string }>;
const versions = db.app_settings.consent_versions as Record<string, string>;
out = ref;
insert('content_versions', [
  ...Object.entries(texts).map(([key, t]) => ({ key, version: versions[key] ?? '1.0', revision: 1, title_en: '', title_ml: '', body_en: t.en, body_ml: t.ml, reason: 'Initial text' })),
  ...LEGAL_DOCUMENTS.map((d) => ({ ...d, version: '1.0', revision: 1, reason: 'Initial draft' })),
], ['key', 'version', 'revision', 'title_en', 'title_ml', 'body_en', 'body_ml', 'reason']);
out = demo;
insert('reschedule_requests', db.reschedule_requests, ['id', 'appointment_id', 'requested_by', 'proposed_slot_id', 'proposed_start_at', 'reason', 'status', 'response_note', 'new_appointment_id', 'created_at', 'responded_at']);
out = ref;
insert('notification_templates', db.notification_templates, ['key', 'channel', 'provider_template_name', 'body_en', 'body_ml', 'variables', 'active', 'category', 'audience', 'channels', 'quiet_hours', 'sms_dlt_template_id', 'description'], {
  variables: (r) => arr(r.variables, 'text'),
  channels: (r) => arr(r.channels, 'notification_channel'),
});
out = demo;
insert('notifications', db.notifications, ['id', 'user_id', 'channel', 'template_key', 'variables', 'rendered_text', 'link', 'to_masked', 'status', 'provider_message_id', 'read_at', 'created_at']);
insert('ratings', db.ratings, ['id', 'appointment_id', 'doctor_id', 'patient_id', 'stars', 'comment', 'created_at']);
insert('support_tickets', db.support_tickets, ['id', 'user_id', 'appointment_id', 'category', 'subject', 'description', 'status', 'resolution', 'created_at', 'updated_at']);
insert('call_logs', db.call_logs, ['id', 'appointment_id', 'provider', 'room_name', 'event', 'actor_role', 'source', 'detail', 'created_at']);
insert('audit_logs', db.audit_logs, ['id', 'actor_user_id', 'actor_role', 'action', 'entity', 'entity_id', 'before', 'after', 'reason', 'created_at']);
ref.push('commit;');
demo.push('commit;');

return {
  reference: ref.join('\n') + '\n',
  demo: demo.join('\n') + '\n',
  stats: { slots: db.slots.length + extraSlots.length, patients: db.patients.length, doctors: db.doctors.length, appointments: db.appointments.length, drugs: db.drug_master.length, icd10: db.icd10_master.length },
};
}
